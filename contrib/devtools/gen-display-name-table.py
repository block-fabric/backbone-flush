"""The code points a BitAssets display name may hold: writes src/bitassets/displayname_table.h to stdout.

Consensus: the table is frozen at Unicode 15.0 (the Python of the run must have exactly that version).
Usage: contrib/devtools/gen-display-name-table.py > src/bitassets/displayname_table.h
"""
import unicodedata as ud, sys
assert ud.unidata_version == "15.0.0", ud.unidata_version
# Default_Ignorable_Code_Point (DerivedCoreProperties 15.0)
DI = [(0x00AD,0x00AD),(0x034F,0x034F),(0x061C,0x061C),(0x115F,0x1160),(0x17B4,0x17B5),(0x180B,0x180F),
      (0x200B,0x200F),(0x202A,0x202E),(0x2060,0x206F),(0x3164,0x3164),(0xFE00,0xFE0F),(0xFEFF,0xFEFF),
      (0xFFA0,0xFFA0),(0xFFF0,0xFFF8),(0x1BCA0,0x1BCA3),(0x1D173,0x1D17A),(0xE0000,0xE0FFF)]
EXTRA = [(0x2800,0x2800)]  # braille blank: renders as nothing
def di(c): return any(a<=c<=b for a,b in DI+EXTRA)
second=set()
for c in range(0x110000):
    d=ud.decomposition(chr(c))
    if d and not d.startswith('<'):
        p=d.split()
        if len(p)==2: second.add(int(p[1],16))
def ok(c):
    if c < 0x20: return False
    ch=chr(c); cat=ud.category(ch)
    if cat in ('Cc','Cf','Cs','Co','Cn','Zl','Zp','Mn','Mc','Me'): return False
    if cat=='Zs' and c!=0x20: return False
    if ud.combining(ch)!=0: return False
    if ud.normalize('NFC',ch)!=ch: return False
    if c in second: return False
    if 0x1100<=c<=0x11FF or 0xA960<=c<=0xA97F or 0xD7B0<=c<=0xD7FF: return False
    if di(c): return False
    return True
ranges=[]
for c in range(0x110000):
    if ok(c):
        if ranges and ranges[-1][1]==c-1: ranges[-1][1]=c
        else: ranges.append([c,c])
print(len(ranges), file=sys.stderr)
print("// Generated by contrib/devtools/gen-display-name-table.py (Unicode %s): do not edit." % ud.unidata_version)
print("// The code points a display name may hold (bitassets::IsDisplayName), as inclusive ranges.")
print("#ifndef BITCOIN_BITASSETS_DISPLAYNAME_TABLE_H\n#define BITCOIN_BITASSETS_DISPLAYNAME_TABLE_H\n\n#include <cstdint>\n\nnamespace bitassets::detail {")
print("inline constexpr uint32_t DISPLAY_NAME_RANGES[][2]{")
line=""
for a,b in ranges:
    s="{0x%X,0x%X},"%(a,b)
    if len(line)+len(s)>110: print("    "+line); line=""
    line+=s
print("    "+line)
print("};\n} // namespace bitassets::detail\n\n#endif // BITCOIN_BITASSETS_DISPLAYNAME_TABLE_H")
